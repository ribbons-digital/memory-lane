import * as fs from "node:fs"
import * as path from "node:path"
import type { MirrorMemoryRecord } from "./types.js"
import { isGeneratedMirrorIndex, renderMirrorIndexes } from "./indexes.js"
import { mirrorFileName, renderMemoryMarkdown } from "./markdown.js"

export interface ObsidianMirrorSettings {
  vaultPath: string
  folder?: string
}

export interface MirrorSyncResult {
  ok: boolean
  root: string
  created: number
  updated: number
  deleted: number
  warnings: string[]
}

export interface MirrorStatusResult {
  ok: boolean
  root: string
  warnings: string[]
  obsidianVault: boolean
}

function folder(settings: ObsidianMirrorSettings): string {
  return settings.folder?.trim() || "Memory Lane"
}

export function isSafeMirrorFolder(value: string): boolean {
  const trimmed = value.trim()
  return trimmed.length > 0 && !path.isAbsolute(trimmed) && !path.win32.isAbsolute(trimmed) && !trimmed.split(/[\\/]+/u).includes("..")
}

function folderWarning(settings: ObsidianMirrorSettings): string | undefined {
  if (!isSafeMirrorFolder(folder(settings))) {
    return "Mirror folder must be a relative path inside the vault."
  }
  return undefined
}

function mirrorRoot(settings: ObsidianMirrorSettings): string {
  return path.join(settings.vaultPath, folder(settings))
}

function memoriesDir(settings: ObsidianMirrorSettings): string {
  return path.join(mirrorRoot(settings), "memories")
}

function importsDir(settings: ObsidianMirrorSettings): string {
  return path.join(mirrorRoot(settings), "imports")
}

function indexesDir(settings: ObsidianMirrorSettings): string {
  return path.join(mirrorRoot(settings), "indexes")
}

function memoryPath(settings: ObsidianMirrorSettings, memory: MirrorMemoryRecord): string {
  const name = mirrorFileName(memory)
  if (path.basename(name) !== name) throw new Error(`Unsafe memory id for mirror file: ${memory.id}`)
  return path.join(memoriesDir(settings), name)
}

function indexPath(settings: ObsidianMirrorSettings, mirrorIndexPath: string): string {
  const normalized = path.posix.normalize(mirrorIndexPath.replace(/\\/gu, "/"))
  if (
    normalized !== mirrorIndexPath
    || normalized === "."
    || normalized.startsWith("../")
    || normalized.includes("/../")
    || path.isAbsolute(mirrorIndexPath)
    || path.win32.isAbsolute(mirrorIndexPath)
    || !normalized.endsWith(".md")
    || (normalized !== "index.md" && !normalized.startsWith("indexes/"))
  ) {
    throw new Error(`Unsafe mirror index path: ${mirrorIndexPath}`)
  }
  return path.join(mirrorRoot(settings), ...normalized.split("/"))
}

function isActive(memory: MirrorMemoryRecord): boolean {
  return memory.status === "approved" || memory.status === "pending"
}

function generated(content: string): boolean {
  const lines = content.split(/\r?\n/u)
  if (lines[0] !== "---") return false

  const end = lines.findIndex((line, index) => index > 0 && line.trim() === "---")
  if (end === -1) return false

  return lines.slice(1, end).some((line) => /^[ \t]*memory_lane_mirror[ \t]*:[ \t]*true[ \t]*$/u.test(line))
}

function readme(): string {
  return [
    "# Memory Lane",
    "",
    "This folder is generated by Memory Lane from JSONL memory records.",
    "",
    "- Start browsing at `index.md`.",
    "- `indexes/*.md` contains generated views for pending, approved, project, and recent memories.",
    "- `memories/*.md` mirrors active approved and pending JSONL memory records.",
    "- Add import notes under `imports/*.md`, then run `memory-lane obsidian import`.",
    "- JSONL remains the source of truth.",
    "- Generated mirror files are read-only; do not edit `index.md`, `indexes/*.md`, or `memories/*.md` directly because changes may be overwritten.",
    "- Rebuild the mirror with `memory-lane obsidian sync`.",
    "",
  ].join("\n")
}

export function statusObsidianMirror(settings: ObsidianMirrorSettings): MirrorStatusResult {
  const warnings: string[] = []
  let ok = true

  const unsafeFolder = folderWarning(settings)
  if (unsafeFolder) {
    warnings.push(unsafeFolder)
    ok = false
  }

  if (!settings.vaultPath) {
    warnings.push("Vault path is required.")
    ok = false
  } else if (!fs.existsSync(settings.vaultPath)) {
    warnings.push(`Vault path does not exist: ${settings.vaultPath}`)
    ok = false
  } else if (!fs.statSync(settings.vaultPath).isDirectory()) {
    warnings.push(`Vault path is not a directory: ${settings.vaultPath}`)
    ok = false
  }

  const obsidianVault = Boolean(settings.vaultPath) && fs.existsSync(path.join(settings.vaultPath, ".obsidian"))
  if (ok && !obsidianVault) warnings.push("No .obsidian/ directory found; Memory Lane will still write Markdown here.")

  return { ok, root: mirrorRoot(settings), warnings, obsidianVault }
}

export function initObsidianMirror(settings: ObsidianMirrorSettings): MirrorSyncResult {
  const status = statusObsidianMirror(settings)
  if (!status.ok) return { ok: false, root: status.root, created: 0, updated: 0, deleted: 0, warnings: status.warnings }

  fs.mkdirSync(memoriesDir(settings), { recursive: true })
  fs.mkdirSync(importsDir(settings), { recursive: true })
  fs.mkdirSync(indexesDir(settings), { recursive: true })
  const readmePath = path.join(mirrorRoot(settings), "README.md")
  if (!fs.existsSync(readmePath)) fs.writeFileSync(readmePath, readme(), "utf8")

  return { ok: true, root: status.root, created: 0, updated: 0, deleted: 0, warnings: status.warnings }
}

export function syncObsidianMirror(settings: ObsidianMirrorSettings, memories: MirrorMemoryRecord[], opts?: { dryRun?: boolean }): MirrorSyncResult {
  const status = statusObsidianMirror(settings)
  if (!status.ok) return { ok: false, root: status.root, created: 0, updated: 0, deleted: 0, warnings: status.warnings }

  const dryRun = opts?.dryRun === true
  const dir = memoriesDir(settings)
  const indexDir = indexesDir(settings)
  const root = mirrorRoot(settings)
  if (!dryRun) {
    fs.mkdirSync(dir, { recursive: true })
    fs.mkdirSync(importsDir(settings), { recursive: true })
    fs.mkdirSync(indexDir, { recursive: true })
    const readmePath = path.join(root, "README.md")
    if (!fs.existsSync(readmePath)) fs.writeFileSync(readmePath, readme(), "utf8")
  }

  let created = 0
  let updated = 0
  let deleted = 0
  const active = memories.filter(isActive)
  const activeFiles = new Set(active.map(mirrorFileName))

  for (const memory of active) {
    const file = memoryPath(settings, memory)
    const next = renderMemoryMarkdown(memory)
    const exists = fs.existsSync(file)
    const current = exists ? fs.readFileSync(file, "utf8") : undefined
    if (!exists) created++
    else if (current !== next) updated++
    if (!dryRun && (!exists || current !== next)) fs.writeFileSync(file, next, "utf8")
  }

  const indexFiles = renderMirrorIndexes(memories)
  const activeIndexFiles = new Set(
    indexFiles.filter((index) => index.path.startsWith("indexes/")).map((index) => path.basename(index.path)),
  )
  for (const index of indexFiles) {
    const file = indexPath(settings, index.path)
    const exists = fs.existsSync(file)
    const current = exists ? fs.readFileSync(file, "utf8") : undefined
    if (!exists) created++
    else if (current !== index.content) updated++
    if (!dryRun && (!exists || current !== index.content)) {
      fs.mkdirSync(path.dirname(file), { recursive: true })
      fs.writeFileSync(file, index.content, "utf8")
    }
  }

  if (fs.existsSync(dir)) {
    for (const name of fs.readdirSync(dir)) {
      if (!name.endsWith(".md") || activeFiles.has(name)) continue
      const file = path.join(dir, name)
      const stat = fs.lstatSync(file)
      if (!stat.isFile()) continue
      const content = fs.readFileSync(file, "utf8")
      if (!generated(content)) continue
      deleted++
      if (!dryRun) fs.rmSync(file)
    }
  }

  if (fs.existsSync(indexDir)) {
    for (const name of fs.readdirSync(indexDir)) {
      if (!name.endsWith(".md") || activeIndexFiles.has(name)) continue
      const file = path.join(indexDir, name)
      const stat = fs.lstatSync(file)
      if (!stat.isFile()) continue
      const content = fs.readFileSync(file, "utf8")
      if (!isGeneratedMirrorIndex(content)) continue
      deleted++
      if (!dryRun) fs.rmSync(file)
    }
  }

  return { ok: true, root: status.root, created, updated, deleted, warnings: status.warnings }
}

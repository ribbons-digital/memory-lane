const INSTALLER_URL = "https://github.com/ribbons-digital/memory-lane/releases/latest/download/install.sh"
const WINDOWS_INSTALLER_URL = "https://github.com/ribbons-digital/memory-lane/releases/latest/download/install.ps1"
// Internal self-upgrade flag: after installing a new binary, the old running process invokes the new binary with this flag so harness configs are regenerated by fresh code.
const REAPPLY_INSTALL_MANIFEST_FLAG = "--reapply-install-manifest"

export interface ReapplyInstallManifestResult {
  results: IntegrationResult[]
  configuredCount: number
  manifest: InstallManifest
}

export interface ManifestTransaction {
  path: string
  backupPath: string
  existed: boolean
}

export interface UpgradeLock {
  path: string
  owner: string
}

interface UpgradeLockOwner {
  pid: number
  processStartedAt: string
  token: string
  createdAt: number
  heartbeatAt: number
  phase: "starting" | "recovery"
}

export type ProcessStartTimeInspection =
  | { status: "found"; startedAt: string }
  | { status: "missing" }
  | { status: "unknown" }

export interface UpgradeLockOptions {
  now?: () => number
  createToken?: () => string
  staleAfterMs?: number
  inspectProcessStartTime?: (processId: number) => ProcessStartTimeInspection
}

const DEFAULT_UPGRADE_LOCK_STALE_AFTER_MS = 60 * 60 * 1000
const CURRENT_PROCESS_STARTED_AT = String(Math.round(Date.now() - process.uptime() * 1000))

function inspectWindowsProcessStartTime(processId: number): ProcessStartTimeInspection {
  if (process.platform !== "win32") {
    return processId === process.pid
      ? { status: "found", startedAt: CURRENT_PROCESS_STARTED_AT }
      : { status: "missing" }
  }
  const command = [
    "$processId = [int]$env:MEMORY_LANE_UPGRADE_PROCESS_PID",
    "$process = Get-Process -Id $processId -ErrorAction SilentlyContinue",
    "if ($null -eq $process) { [Console]::Out.Write('missing') } else { [Console]::Out.Write($process.StartTime.ToUniversalTime().Ticks) }",
  ].join("; ")
  const result = spawnSync(
    "powershell.exe",
    ["-NoProfile", "-NonInteractive", "-EncodedCommand", Buffer.from(command, "utf16le").toString("base64")],
    {
      encoding: "utf8",
      windowsHide: true,
      env: { ...process.env, MEMORY_LANE_UPGRADE_PROCESS_PID: String(processId) },
    },
  )
  const startedAt = typeof result.stdout === "string" ? result.stdout.trim() : ""
  if (result.status !== 0) return { status: "unknown" }
  if (startedAt === "missing") return { status: "missing" }
  return /^\d+$/u.test(startedAt)
    ? { status: "found", startedAt }
    : { status: "unknown" }
}

function readUpgradeLockOwner(ownerPath: string): UpgradeLockOwner | undefined {
  try {
    const value = JSON.parse(fs.readFileSync(ownerPath, "utf8")) as Partial<UpgradeLockOwner>
    return Number.isInteger(value.pid) && Number(value.pid) > 0
      && typeof value.token === "string" && value.token.length > 0
      && typeof value.createdAt === "number" && Number.isFinite(value.createdAt) && value.createdAt > 0
      && typeof value.heartbeatAt === "number" && Number.isFinite(value.heartbeatAt) && value.heartbeatAt > 0
      && typeof value.processStartedAt === "string" && /^\d+$/u.test(value.processStartedAt)
      && (value.phase === "recovery" || value.phase === "starting")
      ? {
          pid: Number(value.pid),
          processStartedAt: value.processStartedAt,
          token: value.token,
          createdAt: value.createdAt,
          heartbeatAt: value.heartbeatAt,
          phase: value.phase,
        }
      : undefined
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT" || error instanceof SyntaxError) return undefined
    throw error
  }
}

function sameUpgradeLockOwner(left: UpgradeLockOwner | undefined, right: UpgradeLockOwner): boolean {
  return left?.pid === right.pid
    && left.processStartedAt === right.processStartedAt
    && left.token === right.token
    && left.createdAt === right.createdAt
    && left.heartbeatAt === right.heartbeatAt
    && left.phase === right.phase
}

function readLockSnapshot(lockPath: string): { identity: string; modifiedAt: number } | undefined {
  try {
    const stat = fs.statSync(lockPath)
    return { identity: `${stat.dev}:${stat.ino}:${stat.birthtimeMs}`, modifiedAt: stat.mtimeMs }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined
    throw error
  }
}

export function acquireUpgradeLock(
  installDir: string,
  upgradePid: number,
  options: UpgradeLockOptions = {},
): UpgradeLock {
  const lockPath = path.join(installDir, ".memory-lane-upgrade.lock")
  const ownerPath = path.join(lockPath, "owner")
  const now = options.now ?? Date.now
  const staleAfterMs = options.staleAfterMs ?? DEFAULT_UPGRADE_LOCK_STALE_AFTER_MS
  const inspectProcessStartTime = options.inspectProcessStartTime ?? inspectWindowsProcessStartTime
  const upgradeProcess = inspectProcessStartTime(upgradePid)
  if (upgradeProcess.status !== "found" || !/^\d+$/u.test(upgradeProcess.startedAt)) {
    throw new Error("Could not identify the running upgrade process.")
  }
  const processStartedAt = upgradeProcess.startedAt
  const owner = (options.createToken ?? randomUUID)()
  fs.mkdirSync(installDir, { recursive: true })

  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      fs.mkdirSync(lockPath)
      const temporaryOwnerPath = path.join(lockPath, `owner.${owner}.tmp`)
      try {
        const createdAt = now()
        fs.writeFileSync(
          temporaryOwnerPath,
          JSON.stringify({ pid: upgradePid, processStartedAt, token: owner, createdAt, heartbeatAt: createdAt, phase: "starting" }),
          { encoding: "utf8", flag: "wx" },
        )
        fs.renameSync(temporaryOwnerPath, ownerPath)
      } catch (error) {
        fs.rmSync(lockPath, { recursive: true, force: true })
        throw error
      }
      return { path: lockPath, owner }
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error
    }

    const existingOwner = readUpgradeLockOwner(ownerPath)
    const snapshot = readLockSnapshot(lockPath)
    if (!snapshot) continue
    const leaseUpdatedAt = existingOwner?.heartbeatAt ?? snapshot.modifiedAt
    const stale = now() - leaseUpdatedAt >= staleAfterMs
    const ownerProcess = existingOwner ? inspectProcessStartTime(existingOwner.pid) : undefined
    const reclaimable = existingOwner
      ? ownerProcess?.status === "missing"
        || (ownerProcess?.status === "found" && ownerProcess.startedAt !== existingOwner.processStartedAt)
      : stale
    if (!reclaimable) {
      if (!existingOwner) {
        throw new Error("Another Memory Lane upgrade is starting; lock owner metadata is not yet available.")
      }
      if (sameUpgradeLockOwner(readUpgradeLockOwner(ownerPath), existingOwner)) {
        throw new Error(`Another Memory Lane upgrade is already in progress (PID ${existingOwner.pid}).`)
      }
      continue
    }

    const reclaimPath = path.join(lockPath, ".reclaim")
    try {
      fs.writeFileSync(
        reclaimPath,
        JSON.stringify({ pid: upgradePid, processStartedAt, token: owner, createdAt: now(), heartbeatAt: now(), phase: "starting" }),
        { encoding: "utf8", flag: "wx" },
      )
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code
      if (code === "ENOENT") continue
      if (code !== "EEXIST") throw error

      const existingClaim = readUpgradeLockOwner(reclaimPath)
      const claimSnapshot = readLockSnapshot(reclaimPath)
      if (claimSnapshot && now() - (existingClaim?.createdAt ?? claimSnapshot.modifiedAt) >= staleAfterMs) {
        const currentClaimSnapshot = readLockSnapshot(reclaimPath)
        const claimStillMatches = existingClaim
          ? sameUpgradeLockOwner(readUpgradeLockOwner(reclaimPath), existingClaim)
          : readUpgradeLockOwner(reclaimPath) === undefined
            && currentClaimSnapshot?.identity === claimSnapshot.identity
        if (claimStillMatches) fs.rmSync(reclaimPath, { force: true })
      }
      continue
    }

    const currentSnapshot = readLockSnapshot(lockPath)
    const ownerStillMatches = existingOwner
      ? sameUpgradeLockOwner(readUpgradeLockOwner(ownerPath), existingOwner)
      : readUpgradeLockOwner(ownerPath) === undefined && currentSnapshot?.identity === snapshot.identity
    if (!ownerStillMatches) {
      fs.rmSync(reclaimPath, { force: true })
      continue
    }

    const quarantinePath = `${lockPath}.stale.${process.pid}.${now()}.${attempt}`
    try {
      fs.renameSync(lockPath, quarantinePath)
      fs.rmSync(quarantinePath, { recursive: true, force: true })
    } catch (renameError) {
      if ((renameError as NodeJS.ErrnoException).code !== "ENOENT") throw renameError
    }
  }
  throw new Error("Could not acquire the Memory Lane upgrade lock.")
}

export function releaseUpgradeLock(lock: UpgradeLock | undefined): void {
  if (!lock) return
  const owner = readUpgradeLockOwner(path.join(lock.path, "owner"))
  if (owner?.token === lock.owner && owner.phase === "starting") {
    fs.rmSync(lock.path, { recursive: true, force: true })
  }
}

export function snapshotInstallManifest(dataDir: string, upgradePid: number): ManifestTransaction {
  const manifestPath = installManifestPath(dataDir)
  const backupPath = `${manifestPath}.upgrade.${upgradePid}`
  const existed = fs.existsSync(manifestPath)
  if (existed) fs.copyFileSync(manifestPath, backupPath)
  return { path: manifestPath, backupPath, existed }
}

export function installerEnvironment(
  baseEnv: NodeJS.ProcessEnv,
  installDir?: string,
  upgradePid?: number,
  manifestTransaction?: ManifestTransaction,
  upgradeLock?: UpgradeLock,
): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = installDir ? { ...baseEnv, INSTALL_DIR: installDir } : { ...baseEnv }
  if (upgradePid !== undefined) env.MEMORY_LANE_UPGRADE_PID = String(upgradePid)
  if (manifestTransaction) {
    env.MEMORY_LANE_UPGRADE_MANIFEST_PATH = manifestTransaction.path
    env.MEMORY_LANE_UPGRADE_MANIFEST_BACKUP_PATH = manifestTransaction.backupPath
    env.MEMORY_LANE_UPGRADE_MANIFEST_EXISTED = String(manifestTransaction.existed)
  }
  if (upgradeLock) {
    env.MEMORY_LANE_UPGRADE_LOCK_PATH = upgradeLock.path
    env.MEMORY_LANE_UPGRADE_LOCK_OWNER = upgradeLock.owner
  }
  return env
}

function runInstaller(
  scriptPath: string,
  installDir?: string,
  upgradePid?: number,
  manifestTransaction?: ManifestTransaction,
  upgradeLock?: UpgradeLock,
): boolean {
  const isWindows = os.platform() === "win32"
  const env = installerEnvironment(process.env, installDir, upgradePid, manifestTransaction, upgradeLock)
  const result = isWindows
    ? spawnSync("powershell", ["-ExecutionPolicy", "Bypass", "-File", scriptPath], { stdio: "inherit", env })
    : spawnSync("sh", [scriptPath], { stdio: "inherit", env })
  return result.status === 0
}

function finalizeWindowsUpgrade(
  scriptPath: string,
  action: "Commit" | "Rollback",
  installDir?: string,
  manifestTransaction?: ManifestTransaction,
  upgradeLock?: UpgradeLock,
): boolean {
  const env = installerEnvironment(process.env, installDir, process.pid, manifestTransaction, upgradeLock)
  return spawnSync(
    "powershell",
    ["-ExecutionPolicy", "Bypass", "-File", scriptPath, "-UpgradeAction", action],
    { stdio: "inherit", env },
  ).status === 0
}

function downloadWithCurl(url: string, dest: string): boolean {
  const result = spawnSync("curl", ["-fsSL", url, "-o", dest], { stdio: "inherit" })
  return result.status === 0
}

function downloadWithWget(url: string, dest: string): boolean {
  const result = spawnSync("wget", ["-q", url, "-O", dest], { stdio: "inherit" })
  return result.status === 0
}

function canRun(cmd: string): boolean {
  return spawnSync(cmd, ["--version"], { stdio: "ignore" }).status === 0
}

function download(url: string, dest: string): boolean {
  if (canRun("curl")) return downloadWithCurl(url, dest)
  if (canRun("wget")) return downloadWithWget(url, dest)
  return false
}

function runInit(binaryPath: string, yes: boolean): boolean {
  const args = yes ? ["init", "--yes"] : ["init"]
  return spawnSync(binaryPath, args, { stdio: "inherit" }).status === 0
}

export function defaultInstalledBinaryPath(
  homeDir: string,
  isWindows: boolean,
  pathApi: PathApi = isWindows ? path.win32 : path,
): string {
  return isWindows
    ? pathApi.join(homeDir, "bin", "memory-lane.exe")
    : pathApi.join(homeDir, ".local", "bin", "memory-lane")
}

export function reapplyManifestWithInstalledBinary(
  binaryPath: string,
  yes: boolean,
  spawn: typeof spawnSync = spawnSync,
): boolean {
  const args = ["upgrade", REAPPLY_INSTALL_MANIFEST_FLAG]
  if (yes) args.push("--yes")
  return spawn(binaryPath, args, { stdio: "inherit" }).status === 0
}

const KNOWN_HARNESSES: readonly Harness[] = ["claude-code-cli", "codex-cli", "claude-desktop", "codex-desktop", "pi", "omp"]

function isKnownHarness(harness: string): harness is Harness {
  return (KNOWN_HARNESSES as readonly string[]).includes(harness)
}

function manifestError(result: Extract<InstallManifestReadResult, { status: "malformed" | "partial" }>): Error {
  return new Error(result.warnings.join(" "))
}

export function resolveInstallerDirectory(
  binaryPath: string,
  isWindows: boolean,
  hasManifest: boolean,
  pathApi: PathApi = isWindows ? path.win32 : path,
): string | undefined {
  return isWindows || hasManifest ? pathApi.dirname(binaryPath) : undefined
}

export function resolveUpgradeBinaryPath(
  result: InstallManifestReadResult,
  homeDir: string,
  isWindows: boolean,
  pathApi: PathApi = isWindows ? path.win32 : path,
): string {
  if (result.status === "missing") return defaultInstalledBinaryPath(homeDir, isWindows, pathApi)
  if (result.status === "malformed" || result.status === "partial") throw manifestError(result)

  const validated = validateAbsoluteManifestPath(result.manifest.binaryPath, "Install manifest binaryPath", pathApi)
  if (!validated.ok) throw new Error(validated.warning)
  const basename = pathApi.basename(validated.value)
  const managed = isWindows ? basename.toLowerCase() === "memory-lane.exe" : basename === "memory-lane"
  if (!managed) {
    throw new Error(`Install manifest binaryPath is not managed by the release installer: ${validated.value}`)
  }
  return validated.value
}

function validatedManifestDataDir(manifest: InstallManifest, expectedDataDir: string, isWindows: boolean): string {
  const validated = validateAbsoluteManifestPath(manifest.dataDir, "Install manifest dataDir")
  if (!validated.ok) throw new Error(validated.warning)
  const expected = path.normalize(expectedDataDir)
  const matches = isWindows
    ? validated.value.toLowerCase() === expected.toLowerCase()
    : validated.value === expected
  if (!matches) throw new Error(`Install manifest dataDir does not match the active data directory: ${validated.value}`)
  return validated.value
}

function installPreviouslyConfigured(
  options: InitOptions,
  manifest: InstallManifest,
): { results: IntegrationResult[]; replacements: InstallManifestEntry[] } {
  const results: IntegrationResult[] = []
  const replacements: InstallManifestEntry[] = []
  const seen = new Set<string>()

  for (const integration of manifest.integrations) {
    const harness = integrationHarness(integration)
    if (!harness || seen.has(harness)) continue
    seen.add(harness)
    if (!isKnownHarness(harness)) {
      const message = `Unknown harness: ${harness}`
      results.push({ harness: harness as Harness, configured: false, message })
      console.log(`  - ${harness} skipped: ${message}`)
      continue
    }

    try {
      const result = harness === "omp"
        ? (() => {
            const validated = validateOmpExtensionConfigPath(integration.configPath)
            if (!validated.ok) throw new Error(validated.warning)
            return installOmp(options, validated.value)
          })()
        : installHarness(harness, options)
      results.push(result)
      if (result.configPath) replacements.push({ harness: result.harness, configPath: result.configPath })
      console.log(`  ✓ ${harness} reconfigured`)
      if (result.message) console.log(`    ${result.message}`)
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error)
      results.push({ harness, configured: false, message })
      console.log(`  ✗ ${harness} failed: ${message}`)
    }
  }
  return { results, replacements }
}

export function reapplyInstallManifest(
  options: InitOptions,
  manifest: InstallManifest,
  transactional = os.platform() === "win32",
): ReapplyInstallManifestResult {
  validateManifestOmpConfigPaths(manifest)
  const { results, replacements } = installPreviouslyConfigured(options, manifest)
  const configuredCount = results.filter((result) => result.configured).length
  const nextManifest: InstallManifest = {
    ...manifest,
    version: VERSION,
    installedAt: new Date().toISOString(),
    binaryPath: options.binaryPath,
    dataDir: options.dataDir,
    integrations: mergeManifestIntegrations(manifest.integrations, replacements),
  }
  if (configuredCount > 0 && (!transactional || results.every((result) => result.configured))) {
    writeInstallManifest(options.dataDir, nextManifest)
  }
  return { results, configuredCount, manifest: nextManifest }
}

export async function handleUpgrade(argv: string[]): Promise<void> {
  const yes = argv.includes("--yes")
  const reapplyOnly = argv.includes(REAPPLY_INSTALL_MANIFEST_FLAG)
  const isWindows = os.platform() === "win32"
  const url = isWindows ? WINDOWS_INSTALLER_URL : INSTALLER_URL
  const homeDir = process.env.HOME || os.homedir()
  const dataDir = path.join(homeDir, ".memory-lane")
  const manifestResult = readInstallManifest(dataDir)
  const binaryPath = resolveUpgradeBinaryPath(manifestResult, homeDir, isWindows)
  const manifest = manifestResult.status === "valid" ? manifestResult.manifest : undefined
  if (manifest) {
    validatedManifestDataDir(manifest, dataDir, isWindows)
    validateManifestOmpConfigPaths(manifest)
  }

  if (reapplyOnly) {
    if (!manifest) {
      console.log("No previous install manifest found. Run `memory-lane init` to set up integrations.")
      return
    }
    if (manifest.integrations.length === 0) {
      console.log("The install manifest is valid but contains no integrations. Run `memory-lane init` to set up integrations.")
      return
    }
    const options: InitOptions = {
      binaryPath,
      dataDir,
      projectMode: false,
      yes: true,
      homeDir,
      env: process.env,
    }
    const { results, configuredCount } = reapplyInstallManifest(options, manifest)
    const failedIntegrations = results.filter((result) => !result.configured)
    if (configuredCount === 0) {
      throw new Error("No previous harness configs were reapplied. Run `memory-lane init` to inspect integrations.")
    }
    if (failedIntegrations.length > 0) {
      throw new Error(`Failed to reapply ${failedIntegrations.length} required harness configuration(s).`)
    }
    console.log(`Reapplied ${configuredCount} harness configuration(s).`)
    return
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "memory-lane-upgrade-"))
  const scriptPath = path.join(tmpDir, isWindows ? "install.ps1" : "install.sh")
  let pendingWindowsUpgrade = false
  let installDir: string | undefined
  let manifestTransaction: ManifestTransaction | undefined
  let upgradeLock: UpgradeLock | undefined
  let preserveUpgradeLock = false
  const commitWindowsUpgrade = (): void => {
    if (!pendingWindowsUpgrade) return
    if (!finalizeWindowsUpgrade(scriptPath, "Commit", installDir, manifestTransaction, upgradeLock)) {
      throw new Error("Could not finalize the Windows upgrade.")
    }
    pendingWindowsUpgrade = false
  }
  try {
    console.log("Downloading latest installer...")
    if (!download(url, scriptPath)) {
      console.error("Failed to download installer. Please upgrade manually:")
      console.error(`  ${isWindows ? "irm" : "curl -fsSL"} ${url} ${isWindows ? "| iex" : "| sh"}`)
      console.error("  memory-lane init --yes")
      process.exit(1)
    }

    console.log("Running installer...")
    installDir = resolveInstallerDirectory(binaryPath, isWindows, manifest !== undefined)
    upgradeLock = isWindows ? acquireUpgradeLock(installDir!, process.pid) : undefined
    manifestTransaction = isWindows ? snapshotInstallManifest(dataDir, process.pid) : undefined
    if (!runInstaller(scriptPath, installDir, isWindows ? process.pid : undefined, manifestTransaction, upgradeLock)) {
      if (isWindows) {
        const restored = finalizeWindowsUpgrade(scriptPath, "Rollback", installDir, manifestTransaction, upgradeLock)
        if (!restored) {
          preserveUpgradeLock = true
          console.error("Failed to restore the previous Windows executable.")
        } else if (manifestTransaction) {
          fs.rmSync(manifestTransaction.backupPath, { force: true })
        }
      }
      throw new Error("Installer failed. Please check the output above.")
    }
    pendingWindowsUpgrade = isWindows

    if (manifest && manifest.integrations.length > 0) {
      console.log("\nRe-configuring previously installed harnesses...")

      if (!reapplyManifestWithInstalledBinary(binaryPath, yes)) {
        throw new Error("Reconfiguring harnesses with the newly installed binary failed.")
      }
      commitWindowsUpgrade()
      console.log("Upgrade complete.")
      return
    }

    if (manifest) {
      commitWindowsUpgrade()
      console.log("\nThe install manifest is valid but contains no integrations. Upgrade complete.")
      return
    }

    console.log("\nNo previous install manifest found. Running first-time setup...")
    if (!runInit(binaryPath, yes)) {
      throw new Error("Init failed after upgrade.")
    }
    commitWindowsUpgrade()
    console.log("\nUpgrade complete.")
  } catch (error) {
    if (pendingWindowsUpgrade) {
      if (!finalizeWindowsUpgrade(scriptPath, "Rollback", installDir, manifestTransaction, upgradeLock)) {
        preserveUpgradeLock = true
        console.error("Failed to restore the previous Windows executable.")
      }
      pendingWindowsUpgrade = false
    }
    throw error
  } finally {
    if (!preserveUpgradeLock) releaseUpgradeLock(upgradeLock)
    fs.rmSync(tmpDir, { recursive: true, force: true })
  }
}

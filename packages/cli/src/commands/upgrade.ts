const INSTALLER_URL = "https://github.com/ribbons-digital/memory-lane/releases/latest/download/install.sh"
const WINDOWS_INSTALLER_URL = "https://github.com/ribbons-digital/memory-lane/releases/latest/download/install.ps1"
// Internal self-upgrade flag: after installing a new binary, the old running process invokes the new binary with this flag so harness configs are regenerated by fresh code.
const REAPPLY_INSTALL_MANIFEST_FLAG = "--reapply-install-manifest"
const TRANSACTIONAL_WINDOWS_UPGRADE_FLAG = "--transactional-windows-upgrade"

